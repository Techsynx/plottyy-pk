// Helper to populate joins
export function getHydratedListings(): Listing[] {
  return LISTINGS_DATA.map((item) => {
    const city = CITIES_DATA.find((c) => c.id === item.city_id);
    const location = LOCATIONS_DATA.find((l) => l.id === item.location_id);
    const user = PROFILES_DATA.find((p) => p.id === item.user_id);
    return {
      ...item,
      city,
      location: location ? { ...location, city } : undefined,
      user,
    };
  });
}

export function getHydratedListingBySlug(slug: string): Listing | null {
  const listing = LISTINGS_DATA.find((l) => l.slug === slug);
  if (!listing) return null;
  const city = CITIES_DATA.find((c) => c.id === listing.city_id);
  const location = LOCATIONS_DATA.find((l) => l.id === listing.location_id);
  const user = PROFILES_DATA.find((p) => p.id === listing.user_id);
  return {
    ...listing,
    city,
    location: location ? { ...location, city } : undefined,
    user,
  };
}

export function getHydratedLeads(): Lead[] {
  return LEADS_DATA.map((lead) => {
    const listing = getHydratedListings().find((l) => l.id === lead.listing_id);
    return {
      ...lead,
      listing,
    };
  });
}
